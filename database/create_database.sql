-- Создание базы данных для системы "Благотворительный фонд".
-- Выполняется один раз от пользователя postgres, до первого запуска программы.
--
-- Локаль ru_RU.UTF-8 нужна, чтобы функция LOWER() корректно работала с кириллицей
-- (поиск без учёта регистра). С локалью 'C' поиск по русским словам не находит записи.

CREATE DATABASE charity_fund
    TEMPLATE template0
    ENCODING 'UTF8'
    LC_COLLATE 'ru_RU.UTF-8'
    LC_CTYPE 'ru_RU.UTF-8';

