package ru.mirea.fund.util; // Пакет вспомогательных классов: подключение к базе и экспорт данных.

import ru.mirea.fund.model.Donation; // Класс-сущность: список пожертвований уходит в файл.
import ru.mirea.fund.model.Donor; // Класс-сущность: список доноров уходит в файл.

import java.util.List; // Оба набора данных приходят в экспортёр списками.

// Интерфейс экспорта данных фонда — второй интерфейс в проекте.
//
// Смысл: меню не должно знать, КУДА и КАК сохраняются данные. Оно работает
// с переменной типа Exporter, а за ней может стоять и ExcelExporter, и CsvExporter.
// Это полиморфизм: один вызов exporter.export(...) выполняет разный код
// в зависимости от того, какой объект туда положили.
//
// Если завтра понадобится экспорт в PDF — достаточно написать PdfExporter,
// реализующий этот интерфейс. Остальной код менять не придётся.
public interface Exporter {

    String export(List<Donor> donors, List<Donation> donations); // Записывает данные в файл и возвращает полный путь к нему, чтобы показать пользователю.

    String getFormatName(); // Название формата: меню печатает его в сообщении об успешном экспорте.
}
